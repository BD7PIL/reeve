export const CATALOGS = { en: EN, 'zh-CN': ZH }

let locale = 'en'

/** 宿主 locale → 本面板支持的两种语言之一（其它一律英文）。 */
export function normalizeLocale(value) {
  return typeof value === 'string' && /^zh(?:-|_|$)/i.test(value) ? 'zh-CN' : 'en'
}

export function setLocale(value) {
  locale = normalizeLocale(value)
  return locale
}

export const getLocale = () => locale
export const isZh = () => locale === 'zh-CN'

/** 取一条文案；`vars` 用 `{name}` 占位。zh-CN 缺项回退英文；英文也缺就显示 key。 */
export function t(key, vars = null) {
  const table = locale === 'zh-CN' ? ZH : EN
  let out = table[key] ?? EN[key] ?? key
  if (vars) {
    out = out.replace(/\{(\w+)\}/g, (whole, name) => (vars[name] == null ? whole : String(vars[name])))
  }
  return out
}

/** 英文单复数：`key.one` / `key.other`；中文两档同文。 */
export function tn(key, n, vars = {}) {
  return t(`${key}.${Number(n) === 1 ? 'one' : 'other'}`, { n, ...vars })
}

/** fallback-edit 的 problem（`{code, params}`）→ 一句本地化文案。 */
export function problemText(problem) {
  if (typeof problem === 'string') return problem
  if (!problem || typeof problem !== 'object') return String(problem)
  return t(problem.code, problem.params ?? {})
}
